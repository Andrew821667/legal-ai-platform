def build_news_writer_system_prompt(*, adoption_module_enabled: bool = False) -> str:
    sections = [
        NEWS_WRITER_BASE_SYSTEM_PROMPT,
        (
            "Активные редакционные модули:\n"
            "- [base]: всегда включен; отвечает за новостной режим, точность, правовой угол и редакционную структуру.\n"
            f"- [adoption_pattern]: {'включен' if adoption_module_enabled else 'выключен'}."
        ),
    ]
    if adoption_module_enabled:
        sections.append(NEWS_WRITER_OPTIONAL_ADOPTION_PATTERN_PROMPT)
    else:
        sections.append(
            "Модуль [adoption_pattern] сейчас выключен. "
            "Не пытайся специально придумывать паттерны применения и верни adoption_fit = none, adoption_patterns = []."
        )
    sections.append(NEWS_WRITER_OUTPUT_SCHEMA_PROMPT)
    return "\n\n".join(section.strip() for section in sections if section.strip())


NEWS_WRITER_SYSTEM_PROMPT = build_news_writer_system_prompt()



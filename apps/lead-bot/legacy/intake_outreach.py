"""Первое обращение к клиенту после юридической заявки.

Человек оставил заявку и ждёт. Задача этого сообщения — показать, что его
обращение попало к людям, а не в очередь: назвать, что именно мы поняли из
описания, и предложить помощь в подготовке.

Тон здесь важнее содержания. Пишем как коллега, который взялся за задачу:
без канцелярита, без продающих оборотов, без обещаний результата. Ничего не
оцениваем по существу — оценка ситуации остаётся за юристом.
"""

from __future__ import annotations

_AREA_WORDS = {
    "contracts": "договорной работы",
    "corporate": "корпоративных вопросов",
    "labor": "трудовых отношений",
    "realty": "недвижимости",
    "family": "семейных отношений",
    "debt": "взыскания задолженности",
    "court": "судебного спора",
    "tax": "налоговых вопросов",
    "other": "вашей ситуации",
}

_CLIENT_GREETING = {
    "business": "Здравствуйте!",
    "individual": "Здравствуйте!",
    "unknown": "Здравствуйте!",
}


def build_outreach_message(intake: dict) -> str:
    """Собирает первое сообщение клиенту.

    Сообщение обращается к сути заявки, но не пересказывает её целиком: человек
    и так знает, что написал, а дословный повтор выглядит машинным.
    """
    name = str(intake.get("name") or "").strip()
    area = _AREA_WORDS.get(str(intake.get("legal_area") or "other"), "вашей ситуации")
    client_type = str(intake.get("client_type") or "unknown")
    urgent = str(intake.get("urgency") or "") == "urgent"

    greeting = _CLIENT_GREETING.get(client_type, "Здравствуйте!")
    if name:
        greeting = f"{greeting.rstrip('!')}, {name}!"

    lines = [
        greeting,
        "",
        # Представляемся честно. Если клиент считает, что пишет юристу, он может
        # раскрыть детали, полагаясь на адвокатскую тайну, — а её здесь нет.
        # Юрист подключается отдельно, и человек должен понимать, когда это
        # произошло.
        "Это ассистент команды AI Verdict. "
        f"Ваше обращение по вопросам {area} получено, юрист его уже смотрит.",
        "",
    ]

    if urgent:
        lines.append(
            "Вы отметили, что вопрос срочный, поэтому не буду тянуть: "
            "чем раньше мы увидим детали, тем быстрее юрист сможет включиться."
        )
    else:
        lines.append(
            "Чтобы разговор с юристом был предметным, полезно заранее "
            "разобраться в деталях."
        )

    lines.extend(
        [
            "",
            "Могу помочь подготовиться к разговору: уточню обстоятельства и "
            "подскажу, какие документы пригодятся. Это займёт несколько минут "
            "и сэкономит время на самой консультации.",
            "",
            "Начнём? Если удобнее сразу с юристом — просто напишите об этом.",
        ]
    )
    return "\n".join(lines)


def build_no_contact_note(intake: dict) -> str:
    """Сообщение юристу о том, что клиенту нельзя написать первым."""
    return "\n".join(
        [
            "⚠️ НЕ УДАЛОСЬ СВЯЗАТЬСЯ С КЛИЕНТОМ",
            "",
            "Обращение пришло не из Telegram, поэтому бот не может написать "
            "первым — это ограничение Telegram, а не сбой.",
            "",
            f"Обращение: {intake.get('intake_id')}",
            f"Имя: {intake.get('name') or 'не указано'}",
            "",
            "Связаться нужно вручную по контакту из карточки обращения.",
        ]
    )

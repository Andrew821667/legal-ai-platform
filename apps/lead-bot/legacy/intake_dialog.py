def build_document_accepted(*, count: int, nda_signed: bool) -> str:
    """Подтверждение получения документа."""
    word = "документ" if count == 1 else "документа" if 2 <= count <= 4 else "документов"
    line = f"Получил, всего {count} {word}."
    if not nda_signed:
        line += " Отметил в карточке, что соглашение о конфиденциальности не подписывалось."
    return f"{line}\n\nЕсли есть ещё — присылайте. Закончили — напишите «готово»."


def build_handoff(*, documents_count: int, answered_count: int) -> str:
    """Завершение диалога и передача юристу."""
    lines = ["Всё передал юристу."]

    collected: list[str] = []
    if answered_count:
        collected.append("ответы на уточняющие вопросы")
    if documents_count:
        collected.append(f"документы ({documents_count})")
    if collected:
        lines.append(f"В карточке обращения: описание ситуации, {' и '.join(collected)}.")

    lines.extend(
        [
            "",
            "Юрист посмотрит материалы и свяжется с вами. Если удобнее обсудить "
            "голосом — напишите, договоримся о звонке.",
            "",
            "Если вспомните что-то важное, просто напишите сюда — добавлю к обращению.",
        ]
    )
    return "\n".join(lines)



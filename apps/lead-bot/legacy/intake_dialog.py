# Просьба позвать юриста вместо ответов на вопросы. Настаивать в таком случае
# нельзя: это раздражает и выглядит так, будто до человека не достучаться.
#
# Ошибки здесь несимметричны. Не распознать просьбу — небольшая беда: человек
# повторит. А оборвать диалог на середине, приняв за просьбу описание ситуации
# («этот человек не отдаёт деньги», «мне не вернули телефон»), — грубо и
# необъяснимо со стороны клиента. Поэтому одиночные слова вроде «человек» и
# «телефон» в список не входят, а «юрист» срабатывает только в коротком
# сообщении, где он не может быть частью рассказа.
_HANDOFF_PHRASES = (
    "к юристу",
    "с юристом",
    "живой человек",
    "живого человека",
    "живым человеком",
    "оператор",
    "созвон",
    "позвоните",
    "перезвоните",
    "не хочу отвечать",
    "без вопросов",
)

# Короткие ответы вроде «юрист» или «адвокат, пожалуйста» — это просьба, а не
# упоминание по ходу рассказа.
_HANDOFF_WORDS = ("юрист", "адвокат")
_SHORT_MESSAGE_CHARS = 40


def normalize_area(area: str | None) -> str:
    """Приводит область права к известной, чтобы неизвестное значение не роняло диалог."""
    value = str(area or "other").strip()
    return value if value in QUESTIONS else "other"


def questions_for(area: str | None) -> tuple[Question, ...]:
    return QUESTIONS[normalize_area(area)]


def next_question(area: str | None, answered_keys: object) -> Question | None:
    """Следующий неотвеченный вопрос или None, когда их не осталось."""
    answered = set(answered_keys or ())
    for question in questions_for(area):
        if question.key not in answered:
            return question
    return None


def wants_lawyer(text: str | None) -> bool:
    """Просит ли человек прекратить расспросы и передать дело юристу."""
    lowered = (text or "").strip().lower()
    if not lowered:
        return False
    if any(phrase in lowered for phrase in _HANDOFF_PHRASES):
        return True
    if len(lowered) <= _SHORT_MESSAGE_CHARS:
        return any(word in lowered for word in _HANDOFF_WORDS)
    return False


def build_orientation(area: str | None) -> str:
    """Что мы поняли и что обычно нужно дальше.

    Ориентация, а не оценка: называем область права, типичные сроки и
    документы — и явно оставляем разбор ситуации юристу.
    """
    key = normalize_area(area)
    lines = [
        "Спасибо — этого достаточно, чтобы юрист начал предметно.",
        "",
        f"Ваш вопрос относится к области: {AREA_LABEL[key].lower()}.",
    ]

    note = DEADLINE_NOTE[key]
    if note:
        lines.extend(["", note, _DEADLINE_CAVEAT])

    documents = DOCUMENTS[key]
    lines.extend(["", "Обычно по таким вопросам юристу нужны:"])
    lines.extend(f"• {item}" for item in documents)
    lines.extend(
        [
            "",
            "Если чего-то нет — не страшно, это не мешает начать.",
        ]
    )
    return "\n".join(lines)



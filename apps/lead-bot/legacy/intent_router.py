"""Интент-роутер: перед ответом определяем, о чём вообще сообщение.

До этого модуля каждое сообщение вело через воронку discover→diagnose→
qualify→propose по жёстким ключевым словам (funnel.py) — даже когда человек
продолжает своё дело, спрашивает про саму платформу, описывает задачу на
разработку или просто знакомится. Воронка не знает разницы и всё равно
строит «диагностический вывод + один уточняющий вопрос» под покупку системы
для юридического отдела.

Здесь — лёгкая LLM-классификация (ai_brain.classify_intent_async). При сбое
или низкой уверенности — «unclear»: ассистент отвечает по существу, если
может, и задаёт вопрос-развилку (юрист / автоматизация / разработка).
Раньше неуверенность означала воронку продажи автоматизации: человеку с
вопросом по разводу задавали вопрос про число юристов в отделе.
sales_conversation («ничего не меняем» для вызывающего кода) — только когда
модель уверенно видит разговор о внедрении системы.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass

import ai_brain

logger = logging.getLogger(__name__)

INTENTS = (
    "continuing_own_matter",
    "new_legal_task",
    "platform_question",
    "dev_task",
    "browsing",
    "sales_conversation",
    "unclear",
)

SALES_INTENT = "sales_conversation"
UNCLEAR_INTENT = "unclear"
_MIN_CONFIDENCE = 0.5

_FIRST_STEPS_HINT = (
    "Платные первые шаги с фиксированной ценой перечислены в системном промпте; "
    "называй их, когда это уместно, не начинай с цены."
)


@dataclass(frozen=True)
class IntentResult:
    intent: str
    confidence: float
    # None → продажная воронка (funnel.build_stage_context +
    # funnel.enforce_leadgen_response); бывает только у sales_conversation.
    context_override: str | None


def is_confident_sales(result: "IntentResult") -> bool:
    """Докручивать ответ воронкой продажи — только при уверенном sales_conversation."""
    return result.intent == SALES_INTENT and result.confidence >= _MIN_CONFIDENCE


def _context_for(intent: str, *, has_core_context: bool) -> str | None:
    if intent == "continuing_own_matter":
        if not has_core_context:
            # Модель решила, что это продолжение дела, но данных о человеке
            # в ядре нет — подробностей не выдумываем и воронку не ведём.
            return (
                "# Похоже на продолжение своего дела\n"
                "Человек пишет о своём деле, но данных о нём в системе не нашлось. Не выдумывай "
                "подробностей и не задавай вопросов продажной квалификации. Попроси коротко "
                "напомнить суть или номер договора/обращения. Если это новый вопрос — предложи "
                "описать его здесь или кнопкой «⚖️ Юридическая практика»."
            )
        return (
            "# Продолжение своего дела\n"
            "Судя по сообщению, человек продолжает разговор о своём деле, а не начинает "
            "новый холодный контакт. Отвечай по существу его вопроса, используя данные о "
            "нём выше. Не начинай с дискавери-вопросов (размер команды, бюджет, отрасль) — "
            "это не подходит для продолжения уже идущей работы. Если для ответа не хватает "
            "конкретики — уточни только то, что нужно по сути его вопроса."
        )
    if intent == "new_legal_task":
        return (
            "# Новая правовая задача\n"
            "Человек впервые описывает конкретную правовую задачу или вопрос. Дай короткий "
            "содержательный отклик по сути сказанного, затем предложи оформить обращение "
            "юристу — либо кнопкой «⚖️ Юридическая практика», либо прямо продолжив здесь, если "
            "он уже начал описывать задачу. Если нужен разговор с юристом — консультация "
            "4 900 ₽ с записью на сайте; для договора — экспресс-проверка, для претензии — "
            "подготовка претензии. Не веди через воронку продажи автоматизации "
            "(размер команды, объём договоров, бюджет) — это разовая задача клиента, а не "
            "покупка системы для юридического отдела.\n" + _FIRST_STEPS_HINT
        )
    if intent == "dev_task":
        return (
            "# Задача на разработку\n"
            "Человек описывает задачу на разработку (бот, сайт, интеграция, AI-модуль, "
            "программа). Ответь по существу, приведи короткий релевантный пример из "
            "инженерной практики AI Verdict, предложи следующий шаг: описать задачу подробнее "
            "прямо здесь (передадим инженерам) или диагностику автоматизации (7 900 ₽, "
            "засчитывается в бюджет проекта). Не задавай вопросы продажной квалификации, если человек ещё не "
            "сформулировал бюджет и сроки сам.\n" + _FIRST_STEPS_HINT
        )
    if intent == "platform_question":
        return (
            "# Вопрос о платформе\n"
            "Человек спрашивает про саму компанию/платформу/тарифы/устройство сервиса, а не "
            "описывает свою задачу. Ответь прямо и по существу, ссылайся на реальные части "
            "платформы (Contract AI, юридическая и инженерная практики, новостной контур). "
            "Не квалифицируй его как лида и не дави предложением консультации, если он сам "
            "не просит связать с командой."
        )
    if intent == "browsing":
        return (
            "# Знакомство с платформой\n"
            "Человек, похоже, просто знакомится, а не пришёл с конкретной задачей. Будь "
            "лёгким и информативным: коротко покажи, что умеет AI Verdict, без давления "
            "вопросами квалификации. Дай понять, что можно и просто спросить, и сразу "
            "описать задачу."
        )
    if intent == UNCLEAR_INTENT:
        return (
            "# Запрос пока неясен\n"
            "AI Verdict многопрофильный: юридическая помощь по праву РФ, автоматизация "
            "юридической работы и инженерная разработка (боты, сайты, AI-сервисы, интеграции). "
            "Если из сообщения понятна суть — ответь по существу. Если нет — коротко ответь на "
            "сказанное и задай один вопрос-развилку: нужна (1) помощь юриста по конкретной "
            "ситуации, (2) автоматизация юридической работы или (3) разработка бота, сайта, "
            "AI-сервиса. Не спрашивай про размер команды, объём договоров и бюджет."
        )
    return None  # sales_conversation — продажная воронка


async def classify(
    *,
    conversation_history: list[dict],
    has_core_context: bool,
) -> IntentResult:
    """Классифицирует последнее сообщение. Любой сбой классификации, незнакомая
    категория или низкая уверенность — unclear (вопрос-развилка)."""
    try:
        raw = await ai_brain.ai_brain.classify_intent_async(conversation_history)
    except Exception as error:  # noqa: BLE001 — классификация необязательна, ответ важнее
        logger.warning("Intent classification raised, asking the fork question: %s", error)
        raw = None

    intent = raw.get("intent") if isinstance(raw, dict) else None
    if intent not in INTENTS:
        intent = UNCLEAR_INTENT

    confidence = 0.0
    if isinstance(raw, dict):
        try:
            confidence = float(raw.get("confidence") or 0.0)
        except (TypeError, ValueError):
            confidence = 0.0

    if confidence < _MIN_CONFIDENCE:
        intent = UNCLEAR_INTENT

    return IntentResult(
        intent=intent,
        confidence=confidence,
        context_override=_context_for(intent, has_core_context=has_core_context),
    )

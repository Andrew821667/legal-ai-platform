"""Версионируемый договор юридических услуг."""

from __future__ import annotations

from hashlib import sha256

AGREEMENT_VERSION = "2026-09-08.1"

AGREEMENT_TEXT = """ДОГОВОР ВОЗМЕЗДНОГО ОКАЗАНИЯ ЮРИДИЧЕСКИХ УСЛУГ № {number}
Редакция {revision}. Дата предложения: {created_date}.

1. Стороны
Исполнитель: {operator_name}{operator_status}{operator_inn}{operator_details}.
Заказчик: {client_name}{client_org}.

2. Предмет
Исполнитель обязуется оказать Заказчику юридические услуги по вопросу:

{subject}

В состав услуг входит:
{scope}

В услуги не входит, если стороны письменно не согласуют иное:
{exclusions}

Сроки и этапы работы:
{schedule}

3. Стоимость и порядок оплаты
Стоимость услуг: {price}.
Порядок и сроки оплаты: {payment_terms}.

Стоимость не включает государственные пошлины, нотариальные тарифы и иные
расходы третьих лиц. Такие расходы оплачиваются Заказчиком только после их
предварительного согласования.

4. Обязанности Исполнителя
Исполнитель обязуется:
- оказывать услуги добросовестно в согласованном объёме;
- сообщать о существенных обстоятельствах, влияющих на работу;
- сохранять конфиденциальность сведений и материалов Заказчика.

5. Обязанности Заказчика
Заказчик обязуется:
- своевременно передать достоверные документы и сведения;
- сообщать об изменении обстоятельств, влияющих на работу;
- оплатить услуги в согласованном размере и порядке.

6. Отсутствие гарантии результата
Исполнитель не гарантирует конкретный исход дела. Оплачивается работа, а не
результат: исход зависит от обстоятельств, доказательств и позиции суда либо
иного органа.

7. Конфиденциальность и программные инструменты
Ранее подписанное соглашение о конфиденциальности продолжает действовать.
Независимо от него Исполнитель обязан защищать материалы Заказчика в рамках
настоящего договора.

Исполнитель вправе применять программные средства и системы искусственного
интеллекта как вспомогательные инструменты. Юридически значимые выводы и
документы проверяет специалист. Передача конфиденциальных материалов внешнему
обработчику допускается только при наличии законного основания и необходимых
мер защиты.

8. Прекращение
Заказчик вправе отказаться от договора, оплатив фактически понесённые
Исполнителем расходы. Исполнитель вправе отказаться от договора при условии
полного возмещения Заказчику причинённых таким отказом убытков. Для
Заказчика-потребителя сохраняются все права, предоставленные законодательством
о защите прав потребителей.

9. Электронное взаимодействие и подпись
Исполнитель формирует точную редакцию договора и направляет её Заказчику из
административной версии Telegram-бота. Эти действия выполняет уполномоченный
представитель Исполнителя из своей учётной записи Telegram и тем самым
подписывает договор со стороны Исполнителя и предлагает Заказчику заключить его
на изложенных условиях.

Заказчик получает документ в клиентской версии того же Telegram-бота, открывает
его и нажимает кнопку «Подписать договор» из своей учётной записи Telegram с
зафиксированным уникальным идентификатором. Договор считается заключённым после
фиксации этого действия системой Исполнителя.

Лицом, подписавшим документ, считается лицо, которое указало свои ФИО и контакт
при подписании NDA и использовало соответствующую учётную запись Telegram. При
действии от имени организации также указываются должность и основание
полномочий представителя.

Обе стороны обязаны сохранять конфиденциальность средств доступа к своим
учётным записям Telegram. Каждая сторона обязана незамедлительно сообщить
другой стороне об утрате доступа или компрометации учётной записи.

Документ, подписанный указанным способом обеими сторонами, признаётся
равнозначным документу на бумажном носителе с собственноручными подписями.
Исполнитель фиксирует точный текст документа, его контрольную сумму, дату и
время формирования, отправки, просмотра и подписания, идентификаторы учётных
записей сторон и технические данные действий в боте.

10. Заключительные положения
Предложение подписать настоящий договор действительно до {expires_date}
включительно. После истечения этого срока требуется новая редакция условий.
Сообщения по договору направляются через Telegram-бот Исполнителя либо по
контактам, указанным сторонами.

Версия документа: {version}"""


def render_agreement_text(
    *,
    number: str,
    revision: int,
    created_date: str,
    expires_date: str,
    operator_name: str,
    operator_status: str,
    operator_inn: str,
    operator_details: str,
    client_name: str,
    subject: str,
    scope: str,
    exclusions: str,
    schedule: str,
    price: str,
    payment_terms: str,
    client_org: str | None = None,
) -> str:
    """Собирает точный экземпляр договора перед сохранением."""
    return AGREEMENT_TEXT.format(
        number=number,
        revision=revision,
        created_date=created_date,
        expires_date=expires_date,
        operator_name=operator_name or "Исполнитель",
        operator_status=f", {operator_status}" if operator_status else "",
        operator_inn=f", ИНН {operator_inn}" if operator_inn else "",
        operator_details=f", {operator_details}" if operator_details else "",
        client_name=client_name or "Заказчик",
        client_org=f", от имени {client_org}" if client_org else "",
        subject=(subject or "").strip() or "не указан",
        scope=(scope or "").strip() or "не указан",
        exclusions=(exclusions or "").strip() or "не указаны",
        schedule=(schedule or "").strip() or "не указаны",
        price=(price or "").strip() or "не указана",
        payment_terms=(payment_terms or "").strip() or "не указаны",
        version=AGREEMENT_VERSION,
    )


def document_hash(text: str) -> str:
    """Возвращает SHA-256 точного экземпляра."""
    return sha256(text.encode("utf-8")).hexdigest()

"""Отпечаток секрета для использования в качестве ключа кэша.

Голый SHA256 здесь не годится: он быстрый, поэтому отпечаток можно сопоставить
с исходным ключом перебором, если содержимое памяти когда-либо утечёт. Ключи
выпускаются с высокой энтропией, но полагаться на это как на единственную
защиту не стоит.

BLAKE2 с ключом процесса решает это дешевле, чем bcrypt: отпечаток
невоспроизводим без секрета, который живёт только в памяти и меняется при
каждом запуске. Кэши всё равно не переживают перезапуск, поэтому постоянство
секрета не требуется.
"""

from __future__ import annotations

import secrets
from hashlib import blake2b

# Ключ живёт столько же, сколько процесс: кэши в памяти, переносить отпечатки
# между запусками не нужно.
_PROCESS_KEY = secrets.token_bytes(32)


def fingerprint(secret: str) -> str:
    """Возвращает отпечаток секрета, непригодный для обратного подбора."""
    return blake2b(secret.encode("utf-8"), key=_PROCESS_KEY, digest_size=32).hexdigest()

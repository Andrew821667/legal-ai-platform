"""Текст соглашения о конфиденциальности и его версионирование.

Редакция утверждена владельцем практики 4 сентября 2026 года.

Ключевая для механики часть — пункт о признании простой электронной подписи.
Без явного соглашения сторон считать нажатие кнопки подписью (статья 6
Федерального закона № 63-ФЗ) конструкция не имеет силы, поэтому пункт 6 из
текста убирать нельзя — за этим следит тест.

Версия и хеш фиксируются в момент подписания: при споре нужно доказать, какой
именно текст видел клиент. Поэтому текст неизменяем — любая правка означает
новую версию, а не редактирование существующей. Уже поставленные подписи
остаются привязанными к той редакции, которую человек читал.
"""

from __future__ import annotations

from hashlib import sha256

# Версия меняется при любой правке текста: подписи остаются привязанными к той
# редакции, которую человек читал на экране.
#
# Пометки «черновик» здесь быть не должно: версия записывается в каждую подпись,
# и при споре подпись под документом с таким названием выглядела бы слабо.
NDA_VERSION = "2026-09-04.1"

NDA_TEXT = """СОГЛАШЕНИЕ О КОНФИДЕНЦИАЛЬНОСТИ

1. Стороны
Исполнитель — {operator_name}.
Клиент — лицо, подписавшее настоящее соглашение в Telegram-боте Исполнителя.

2. Предмет
Стороны договорились о защите сведений, которые Клиент передаёт Исполнителю в
связи с обращением за юридической помощью: документов, обстоятельств дела,
переписки и иных материалов.

3. Обязательства Исполнителя
Исполнитель обязуется:
— использовать полученные сведения исключительно для работы по обращению
  Клиента;
— не раскрывать их третьим лицам без согласия Клиента, кроме случаев, когда
  раскрытие обязательно по закону;
— обеспечивать разумные меры защиты сведений при хранении и обработке;
— по требованию Клиента прекратить обработку и удалить материалы, если это не
  противоречит требованиям закона.

4. Исключения
Обязательства не распространяются на сведения, которые:
— были общедоступны на момент передачи или стали общедоступны не по вине
  Исполнителя;
— получены Исполнителем от третьих лиц на законных основаниях;
— подлежат раскрытию по требованию уполномоченных органов.

5. Срок
Соглашение действует с момента подписания и сохраняет силу три года после
завершения работы по обращению.

6. Электронная подпись
Стороны признают, что нажатие Клиентом кнопки подписания в Telegram-боте
Исполнителя является простой электронной подписью в значении статьи 6
Федерального закона от 06.04.2011 № 63-ФЗ «Об электронной подписи».

Стороны согласились, что документы, подписанные таким способом, равнозначны
документам на бумажном носителе, подписанным собственноручной подписью.

Подписание фиксируется Исполнителем с указанием даты, времени, идентификатора
аккаунта Клиента в Telegram и контрольной суммы текста настоящего соглашения.

7. Ограничение
Настоящее соглашение регулирует только вопросы конфиденциальности и не является
договором об оказании юридических услуг.

Версия документа: {version}"""


def render_nda_text(operator_name: str) -> str:
    """Возвращает текст соглашения с подставленными реквизитами."""
    return NDA_TEXT.format(operator_name=operator_name or "Исполнитель", version=NDA_VERSION)


def document_hash(text: str) -> str:
    """Контрольная сумма подписанного текста.

    Фиксируется вместе с подписью: она доказывает, что документ не изменился
    после того, как клиент его подписал.
    """
    return sha256(text.encode("utf-8")).hexdigest()
